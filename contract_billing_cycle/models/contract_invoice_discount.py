from odoo import fields, models


class ContractInvoiceDiscount(models.Model):
    _inherit = "contract.invoice.discount"

    is_free_trial = fields.Boolean(
        string="Free Trial Rule",
        default=False,
        readonly=True,
        copy=True,
        help="Technical flag for the rule generated by the free trial.",
    )
    free_trial_consumed = fields.Boolean(
        string="Free Trial Consumed",
        default=False,
        readonly=True,
        copy=False,
        help="Technical flag set when the trial period is skipped because "
        "the invoice total was zero.",
    )
